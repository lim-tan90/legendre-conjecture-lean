#!/usr/bin/env python3
"""Check historical-row coverage and independent typed Lean comparators.

The catalog is a statement/proof map, never an assertion that open claims have
been proved. The generated Lean consumers check numeric exponents, hypotheses
and bridge direction with the Lean kernel. --write refreshes those consumers.
"""
from __future__ import annotations
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/literature-comparators.json"
CHECKS = ROOT / "Legendre/Tests/Literature.lean"


def render_checks(data: dict) -> str:
    text = '''/-
Copyright (c) 2026 The Legendre formalization contributors.
Released under Apache 2.0 license as described in the file LICENSE.
-/
module
import Legendre.Literature

/-! Independent typed consumers generated by `scripts/check_literature.py --write`.
The expected exponents are in the literature catalog, not read from the implementation.
An equivalence or conditional bridge does not prove its open inputs. -/

namespace Legendre.Tests.Literature
open Legendre.Literature

'''
    for row in data["historical_rows"] + data["layer_checks"]:
        term = "\n".join("  " + line for line in row["comparison_term"].splitlines())
        text += (f'/-- {row["title"] if "title" in row else row["id"]}: statement coverage. -/\n'
                 f'theorem comparator_{row["id"]} : {row["comparison_type"]} :=\n{term}\n\n')
        if row.get("proof_witness"):
            text += (f'/-- Closed proof of the historical claim, checked separately from correspondence. -/\n'
                     f'theorem historical_proof_{row["id"]} : {row["expected"]} :=\n'
                     f'  {row["proof_witness"]}\n\n')
    return text + "end Legendre.Tests.Literature\n"


def check_catalog(data: dict) -> list[str]:
    errors = []
    rows = data["historical_rows"]
    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        errors.append("duplicate historical comparator IDs")
    if len(rows) != 17:
        errors.append("expected the 16 historical-table rows plus Legendre's target")
    for readme in ("README.md", "README.zh.md"):
        text = (ROOT / readme).read_text()
        markers = re.findall(r"<!-- comparator:([a-z0-9]+) -->", text)
        if Counter(markers) != Counter(ids):
            errors.append(f"{readme}: historical rows differ from the comparator catalog")
        # Every table row must have a comparator, including future additions.
        lines = text.splitlines()
        first = next(i for i, line in enumerate(lines) if line.startswith("| **Bertrand"))
        table = []
        for line in lines[first:]:
            if not line.startswith("|"):
                break
            table.append(line)
        if len(table) != 16 or any("<!-- comparator:" not in line for line in table):
            errors.append(f"{readme}: historical table has an uncovered row")
    allowed = {"proved", "open", "conditional_open", "conjecture", "computation_unverified"}
    for row in rows:
        if row["claim_status"] not in allowed:
            errors.append(f'{row["id"]}: unknown status')
        if bool(row["proof_witness"]) != (row["claim_status"] == "proved"):
            errors.append(f'{row["id"]}: proof label and witness disagree')
        for key in ("expected", "comparison_type", "comparison_term", "source", "evidence", "locator"):
            if not row.get(key):
                errors.append(f'{row["id"]}: missing {key}')
    if {r["id"] for r in data["layer_checks"]} != {f"layer{i}" for i in range(5)}:
        errors.append("Layer 0--4 coverage is incomplete")
    sources = {"Legendre.lean"} | {str(p.relative_to(ROOT)) for p in (ROOT / "Legendre").rglob("*.lean")}
    if set(data["module_coverage"]) != sources:
        errors.append("module coverage differs from the complete project Lean source inventory")
    for filename, group in data["module_coverage"].items():
        if group not in {"facade", "verification", "comparison", "statements_only", *(f"layer{i}" for i in range(5))}:
            errors.append(f"{filename}: invalid coverage group {group}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--skip-lean", action="store_true", help="use only after lake build compiled both literature consumer modules")
    args = parser.parse_args()
    data = json.loads(CATALOG.read_text())
    errors = check_catalog(data)
    expected = render_checks(data)
    if args.write and not errors:
        CHECKS.write_text(expected)
    if not CHECKS.exists() or CHECKS.read_text() != expected:
        errors.append("typed consumers are stale; run scripts/check_literature.py --write")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if not args.skip_lean:
        for path in ("Legendre/Tests/Literature.lean", "Legendre/Tests/LiteratureRegression.lean"):
            result = subprocess.run(["lake", "env", "lean", path], cwd=ROOT)
            if result.returncode:
                return result.returncode
    counts = Counter(r["claim_status"] for r in data["historical_rows"])
    print(f"LITERATURE OK: {len(data['historical_rows'])}/17 historical comparators; Layer 0--4 covered.")
    print(f"Source inventory: {len(data['module_coverage'])} Lean files classified.")
    print("Historical claim statuses (comparison coverage is not proof): " +
          ", ".join(f"{key}={value}" for key, value in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
